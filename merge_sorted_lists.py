# MERGE SORTED LISTS
# --------------------------------------------------

left = [1, 4, 7, 7]
right = [2, 4, 9]

result = []
a = 0
b = 0

# Compare the current items and take the smaller one
while a < len(left) and b < len(right):
    if left[a] <= right[b]:
        result.append(left[a])
        a += 1
    else:
        result.append(right[b])
        b += 1

# One list may still have values left, so add them to the end
while a < len(left):
    result.append(left[a])
    a += 1

while b < len(right):
    result.append(right[b])
    b += 1

print(result)

